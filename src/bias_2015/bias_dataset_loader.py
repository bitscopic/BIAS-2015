def get_chrom_to_pos_to_alt_to_splice_score(ab_splice_fp):
    """
    AbSplice is a computational tool that predicts the likelihood of aberrant splicing caused by genetic variants across
    49 human tissues using tissue-specific splicing annotations derived from RNA-seq data. It assigns probabilistic 
    scores, with higher values indicating greater disruption potential, making it particularly useful for identifying
    tissue-relevant splicing defects. In the ACMG framework, AbSplice scores support criteria like PVS1 (null variants
    at splice sites), PS3/BS3 (functional evidence), and PP3/BP4 (in silico predictions), enabling precise classification
    of splice-related variants.

    Wagner N, Çelik MH, Hölzlwimmer FR, Mertes C, Prokisch H, Yépez VA, Gagneur J. Aberrant splicing prediction across 
        human tissues. Nat Genet. 2023 May;55(5):861-870. PMID: 37142848
    """
    chrom_to_pos_to_alt_to_splice_score = {}
    with open(ab_splice_fp, 'r') as in_file:
        for line in in_file:
            split_line = line.strip().split("\t")
            if len(split_line) > 4:
                continue
            chrom, pos, mut, score = split_line
            score = float(score)
            alt = mut[2]
            pos = str(int(pos) + 1)  # Convert BED 0-based to VCF 1-based coordinates
            if chrom_to_pos_to_alt_to_splice_score.get(chrom):
                if chrom_to_pos_to_alt_to_splice_score[chrom].get(pos):
                    chrom_to_pos_to_alt_to_splice_score[chrom][pos][alt] = score
                else:
                    chrom_to_pos_to_alt_to_splice_score[chrom][pos] = {alt: score}
            else:
                chrom_to_pos_to_alt_to_splice_score[chrom] = {pos: {alt: score}}
    if not chrom_to_pos_to_alt_to_splice_score:
        print(f"File {ab_splice_fp} does not have any valid entries!")
        sys.exit(1)
    return chrom_to_pos_to_alt_to_splice_score

def get_clinvar_submitter_counts(clinvar_submitter_counts_fp):
    """
    Load precomputed ClinVar pathogenic submitter counts.
    Used by PS4 (Note 2 fallback) to determine how many independent submitters
    classified a variant as pathogenic/likely pathogenic.

    File format (TSV, no header): chrom, pos, ref, alt, pathogenic_count
    Returns: nested dict chrom -> pos -> (ref, alt) -> count
    """
    chrom_to_pos_to_allele_to_count = {}
    with open(clinvar_submitter_counts_fp, 'r') as in_file:
        for line in in_file:
            split_line = line.strip().split("\t")
            if len(split_line) < 5:
                continue
            chrom, pos, ref, alt, count = split_line
            pos = int(pos)
            count = int(count)
            if chrom not in chrom_to_pos_to_allele_to_count:
                chrom_to_pos_to_allele_to_count[chrom] = {}
            if pos not in chrom_to_pos_to_allele_to_count[chrom]:
                chrom_to_pos_to_allele_to_count[chrom][pos] = {}
            chrom_to_pos_to_allele_to_count[chrom][pos][(ref, alt)] = count
    if not chrom_to_pos_to_allele_to_count:
        print(f"File {clinvar_submitter_counts_fp} does not have any valid entries!")
        sys.exit(1)
    return chrom_to_pos_to_allele_to_count


def get_gene_to_vcep_af_rules(vcep_af_cutoffs_fp):
    """
    Load the VCEP AF cutoffs TSV produced by src/preprocessing/generate_vcep_af_cutoffs.py.

    Returns {gene_symbol: {acmg_code: [VcepAfRule, ...]}}. Multiple rules per code
    are allowed (e.g., a code with both Strong and Supporting strength thresholds);
    the classifier picks the strongest that fires.

    The TSV has a header row and these columns (see generate_vcep_af_cutoffs.py):
        gene_symbol, hgnc_id, acmg_code, strength, threshold, comparator, metric,
        population, min_allele_count, gn_id, version, source_url, raw_description
    """
    gene_to_rules = {}
    with open(vcep_af_cutoffs_fp, "r", encoding="utf-8") as in_file:
        header = in_file.readline().rstrip("\n").split("\t")
        try:
            col = {name: header.index(name) for name in [
                "gene_symbol", "acmg_code", "strength", "threshold", "comparator",
                "metric", "population", "min_allele_count", "mode_of_inheritance",
                "gn_id", "version",
            ]}
        except ValueError as exc:
            print(f"File {vcep_af_cutoffs_fp} is missing an expected column: {exc}")
            sys.exit(1)

        for line in in_file:
            if not line.strip():
                continue
            fields = line.rstrip("\n").split("\t")
            if len(fields) < len(header):
                continue
            gene = fields[col["gene_symbol"]].strip()
            code = fields[col["acmg_code"]].strip()
            strength = fields[col["strength"]].strip()
            threshold_str = fields[col["threshold"]].strip()
            min_ac_str = fields[col["min_allele_count"]].strip()

            threshold = None
            if strength != "NotApplicable" and threshold_str:
                try:
                    threshold = float(threshold_str)
                except ValueError:
                    continue

            try:
                min_ac = int(min_ac_str) if min_ac_str else 0
            except ValueError:
                min_ac = 0

            rule = VcepAfRule(
                strength=strength,
                threshold=threshold,
                comparator=fields[col["comparator"]].strip(),
                metric=fields[col["metric"]].strip() or "raw_af",
                population=fields[col["population"]].strip(),
                min_allele_count=min_ac,
                mode_of_inheritance=fields[col["mode_of_inheritance"]].strip(),
                gn_id=fields[col["gn_id"]].strip(),
                version=fields[col["version"]].strip(),
            )
            gene_to_rules.setdefault(gene, {}).setdefault(code, []).append(rule)

    return gene_to_rules


def get_name_to_dataset(file_paths):
    """
    Gather the datasets and format them for easy python consumption
    """
    name_to_dataset = {}
    name_to_dataset['PVS1_gene_name_to_nmd_info'] = get_gene_name_to_nmd_info(file_paths['PVS1_ncbi_ref_seq_hgmd_fp']) # PVS1 NMD-escape check
    name_to_dataset['PVS1_PP3_BP4_BP7_splice_dict'] = get_chrom_to_pos_to_alt_to_splice_score(file_paths['PVS1_PP3_BP4_BP7_splice_fp']) # PVS1/PP3/BP4/BP7 
    name_to_dataset['PS1_gene_mut_to_data'], name_to_dataset['PM5_gene_aa_to_var_data'] = get_gene_mut_to_data(file_paths['PS1_PM5_clinvar_pathogenic_aa_fp']) # PS1/PM5
    name_to_dataset['PS3_lit_gene_mut_to_data']  = get_lit_gene_mut_to_data(file_paths['PS3_literature_gene_aa_fp']) # PS3
    name_to_dataset['PS3_lit_variant_to_data'] = get_lit_variant_to_data(file_paths['PS3_literature_variant_fp']) # PS3
    name_to_dataset['PS4_chrom_to_pos_to_gwas_data'] = get_dbsnpids_to_or(file_paths['PS4_gwas_dbsnp_fp']) # PS4
    if file_paths.get('PS4_clinvar_submitter_counts_fp'):
        name_to_dataset['PS4_clinvar_submitter_counts'] = get_clinvar_submitter_counts(file_paths['PS4_clinvar_submitter_counts_fp']) # PS4 Note 2
    name_to_dataset['PM1_chrom_to_pathogenic_domain_list'] = get_chrom_to_pathogenic_domain_list(file_paths['PM1_chrom_to_pathogenic_domain_list_fp']) # PM1
    name_to_dataset['PM4_BP3_chrom_to_repeat_regions'] = get_chrom_to_repeat_regions(file_paths['PM4_BP3_coding_repeat_region_fp']) # PM4 & BP1
    name_to_dataset['PP2_missense_pathogenic_gene_to_region_list'] = get_missense_pathogenic_gene_to_region_list(file_paths['PP2_missense_pathogenic_gene_to_region_list_fp']) # PP2
    name_to_dataset['BP1_truncating_gene_to_data'] = get_truncating_gene_to_data(file_paths['BP1_truncating_gene_to_data_fp']) # BP1
    if file_paths.get('BA1_BS1_PM2_vcep_af_cutoffs_fp'):
        name_to_dataset['BA1_BS1_PM2_vcep_gene_to_af_rules'] = get_gene_to_vcep_af_rules(file_paths['BA1_BS1_PM2_vcep_af_cutoffs_fp'])
