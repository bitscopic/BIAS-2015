# PVS1 NMD-escape info: per-transcript coordinates used to decide whether a
# truncating variant is predicted to escape nonsense-mediated decay.
# last_exon_range and penult_last50_range are (start, end) genomic tuples or None.
TranscriptNmdInfo = namedtuple(
    'TranscriptNmdInfo',
    ['transcript_id', 'chrom', 'strand', 'last_exon_range', 'penult_last50_range', 'total_aa'],
)


def calculate_nmd_escape_regions(strand, exon_starts, exon_ends, exon_frames):
    """
    Return (last_exon_range, penult_last50_range) — the genomic intervals where a
    premature termination codon (PTC) would escape NMD.

    Per Chang, Imam & Wilkinson (2007) and Lewis, Green & Brenner (2003), NMD is
    not predicted to occur when the PTC lies in the 3′-most exon OR within the
    3′-most 50 nt of the penultimate exon. Coordinates are genomic (0-based
    half-open, matching the RefSeq TSV convention).

    For a single-exon coding transcript the penultimate range is None.
    If no coding exons remain after filtering, returns (None, None).
    """
    coding_exon_starts = []
    coding_exon_ends = []
    for i in range(len(exon_starts)):
        if exon_frames[i] == '-1':
            continue
        coding_exon_starts.append(exon_starts[i])
        coding_exon_ends.append(exon_ends[i])

    if not coding_exon_ends:
        return None, None

    if strand == "+":
        last_exon_range = (coding_exon_starts[-1], coding_exon_ends[-1])
        if len(coding_exon_ends) >= 2:
            penult_end = coding_exon_ends[-2]
            penult_last50_range = (penult_end - 50, penult_end)
        else:
            penult_last50_range = None
    else:  # negative strand — transcript-last exon = genomic-first exon
        last_exon_range = (coding_exon_starts[0], coding_exon_ends[0])
        if len(coding_exon_starts) >= 2:
            penult_start = coding_exon_starts[1]
            penult_last50_range = (penult_start, penult_start + 50)
        else:
            penult_last50_range = None

    return last_exon_range, penult_last50_range


def calculate_total_aa(exon_starts, exon_ends, cds_start, cds_end):
    """
    Return the number of amino acids in the encoded protein (stop codon excluded),
    computed by summing the coding-sequence overlap across all exons.
    """
    cds_length = 0
    for start, end in zip(exon_starts, exon_ends):
        overlap = min(end, cds_end) - max(start, cds_start)
        if overlap > 0:
            cds_length += overlap
    if cds_length < 3:
        return 0
    return (cds_length - 3) // 3


def get_gene_name_to_nmd_info(ncbi_ref_seq_hgmd_fp):
    """
    Load RefSeq (ncbiRefSeqHgmd) records into {gene_name: [TranscriptNmdInfo, ...]},
    keeping one entry per transcript so multi-transcript genes are represented in full.

    Used by PVS1 to decide whether a truncating variant is predicted to escape NMD
    (see calculate_nmd_escape_regions for the biological rule and citations).
    """
    gene_name_to_nmd_info = {}
    with open(ncbi_ref_seq_hgmd_fp, 'r') as in_file:
        for line in in_file:
            fields = line.strip().split("\t")
            transcript_id = fields[1]
            chrom = fields[2]
            strand = fields[3]
            cds_start = int(fields[6])
            cds_end = int(fields[7])
            exon_starts = list(map(int, fields[9].strip()[:-1].split(",")))
            exon_ends = list(map(int, fields[10].strip()[:-1].split(",")))
            gene_name = fields[12]
            exon_frames = fields[-1].split(",")

            last_exon_range, penult_last50_range = calculate_nmd_escape_regions(
                strand, exon_starts, exon_ends, exon_frames
            )
            if last_exon_range is None:
                continue
            total_aa = calculate_total_aa(exon_starts, exon_ends, cds_start, cds_end)
            info = TranscriptNmdInfo(
                transcript_id=transcript_id,
                chrom=chrom,
                strand=strand,
                last_exon_range=last_exon_range,
                penult_last50_range=penult_last50_range,
                total_aa=total_aa,
            )
            gene_name_to_nmd_info.setdefault(gene_name, []).append(info)

    if not gene_name_to_nmd_info:
        print(f"File {ncbi_ref_seq_hgmd_fp} does not have any valid entries!")
        sys.exit(1)
    return gene_name_to_nmd_info


def get_aa_comparator(p_notation):
    """
    AA look like 'Y524S', 'E525K', 'V552fsS26*', we want to compare the first AA and position
    to the current variant
    """
    first_half = ""
    pos_read = True
    nums = ['1', '2', '3', '4', '5', '6', '7', '8', '9', '0']
    for char in p_notation:
        if char in nums:
            pos_read = False
        if not pos_read and char not in nums:
            break
        first_half += char
    return first_half


